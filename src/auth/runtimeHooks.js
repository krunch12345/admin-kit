const REQUIRED_AUTH_HOOKS = [
  'useLoginAdminMutation',
  'useVerify2FAMutation',
  'useEnable2FAMutation',
  'useGetCurrentUserQuery',
]

let authHooks = null
/** @type {null|(() => Promise<unknown>)} */
let requestLogout = null

/**
 * @typedef {object} AdminKitAuthHooks
 * @property {function} useLoginAdminMutation - RTK Query hook for `loginAdmin`.
 * @property {function} useVerify2FAMutation - RTK Query hook for `verify2FA`.
 * @property {function} useEnable2FAMutation - RTK Query hook for `enable2FA`.
 * @property {function} useGetCurrentUserQuery - RTK Query hook for `getCurrentUser`.
 * @property {function(): Promise<unknown>} [requestLogout] - Optional server logout (revoke refresh cookie).
 */

/**
 * Registers auth hooks generated by the app's api (created with `createAuthEndpoints`).
 * Call once right after `createApi` (and after `configureStore` if you pass `requestLogout`).
 * @param {AdminKitAuthHooks} hooks
 */
export const initAdminKitAuth = (hooks) => {
  const missing = REQUIRED_AUTH_HOOKS.filter((name) => typeof hooks?.[name] !== 'function')

  if (missing.length > 0) {
    throw new Error(`initAdminKitAuth: missing hooks: ${missing.join(', ')}`)
  }

  authHooks = hooks
  requestLogout = typeof hooks.requestLogout === 'function' ? hooks.requestLogout : null
}

/**
 * @returns {AdminKitAuthHooks}
 */
export const getAuthHooks = () => {
  if (!authHooks) {
    throw new Error('admin-kit auth hooks are not initialized. Call initAdminKitAuth() after createApi().')
  }

  return authHooks
}

/**
 * @returns {null|(() => Promise<unknown>)}
 */
export const getRequestLogout = () => requestLogout
